#!/usr/bin/env python3
"""Write each unit's and building's sounds into the rules: the `et_sound` rows of db/seed.sql.

    python3 tools/sounds/seed.py           (from app/) rewrite the generated block
    python3 tools/sounds/seed.py --check   report a stale block without writing

Reads tools/sounds/assignment.json (written by assign.py: every type's sound per event, each a
list of the variations of one sound) and replaces the block between the `BEGIN GENERATED
SOUNDS` and `END GENERATED SOUNDS` markers in db/seed.sql. Only Python's standard library.
"""

import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
APP = HERE.parent.parent
ASSIGNMENT = HERE / "assignment.json"
SEED = APP / "db" / "seed.sql"
BEGIN = "-- BEGIN GENERATED SOUNDS"
END = "-- END GENERATED SOUNDS"

# The owner's changes after listening, as (type key, event): gain in percent. Empty until then.
GAINS = {}

EVENTS = {
    "select", "move", "attack", "build", "build_done", "research_done", "train_done", "fire",
    "fight", "moving", "active",
}


def family(name):
    """A sound file name without its variation number."""
    return re.sub(r"\.\d+$", "", name)


def rows(assignment):
    out = []
    for key in sorted(assignment):
        for event, sounds in sorted(assignment[key].items()):
            slot = 0
            match = re.fullmatch(r"fire_slot(\d+)", event)
            if match:
                event, slot = "fire", int(match.group(1))
            if event not in EVENTS:
                sys.exit(f"{key}: unknown event {event}")
            families = {family(s) for s in sounds}
            if len(families) != 1:
                sys.exit(f"{key} {event}: variations of more than one sound: {sounds}")
            gain = GAINS.get((key, event), 100)
            out.append((key, event, slot, families.pop(), gain))
    return out


def block(assignment):
    values = ",\n".join(
        f" ('{k}','{e}',{s},'{f}',{g})" for k, e, s, f, g in rows(assignment)
    )
    return f"""{BEGIN}
-- Generated by tools/sounds/seed.py from tools/sounds/assignment.json; edit that file (or the
-- gains in seed.py), then regenerate. A key missing from the rules fails the load.
WITH v(k,e,s,f,g) AS (VALUES
{values})
INSERT INTO et_sound(entity_type_id,event,slot,sound,gain_pct)
 SELECT (SELECT id FROM def WHERE key=v.k), v.e, v.s, v.f, v.g FROM v;
{END}"""


def main():
    check = "--check" in sys.argv[1:]
    seed = SEED.read_text()
    start, end = seed.find(BEGIN), seed.find(END)
    if start < 0 or end < start:
        sys.exit(f"{SEED}: no generated sounds block")
    new = seed[:start] + block(json.loads(ASSIGNMENT.read_text())) + seed[end + len(END):]
    if check:
        if new != seed:
            sys.exit("db/seed.sql: the generated sounds are stale; run tools/sounds/seed.py")
        return
    if new != seed:
        SEED.write_text(new)


if __name__ == "__main__":
    main()
