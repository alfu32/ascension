#!/usr/bin/env python3
"""Writes THIRD-PARTY-NOTICES.md: the third-party components the game ships, with their licences.

    python3 -I scripts/release/third_party_notices.py [--check]

Reads the Rust dependencies from `cargo metadata` (normal and build dependencies of the
workspace, every platform) and adds the non-Rust components listed below. With --check it only
reports whether the file is up to date (exit 1 if not).
"""
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "THIRD-PARTY-NOTICES.md"

# Components that do not come from Cargo: name, licence, where its licence text is.
OTHERS = [
    ("DejaVu fonts", "Bitstream Vera / Arev font licence (free)", "app/assets/fonts/LICENSE-DejaVu.txt"),
    ("gpui-component (vendored, patched)", "Apache-2.0", "app/vendor/gpui-component/LICENSE-APACHE"),
    ("xattr (vendored, patched)", "MIT OR Apache-2.0", "app/vendor/xattr/LICENSE-MIT"),
    ("AppImage type2 runtime (Linux AppImage only)", "MIT", "packaging/appimage-inputs.json"),
    ("squashfuse (Linux AppImage only)", "BSD-2-Clause", "packaging/appimage-inputs.json"),
    ("zstd (Linux AppImage only)", "BSD-3-Clause OR GPL-2.0", "packaging/appimage-inputs.json"),
    ("mimalloc (Linux AppImage only)", "MIT", "packaging/appimage-inputs.json"),
]


def rust_dependencies() -> list[dict]:
    meta = json.loads(subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked", "--offline"],
        cwd=ROOT / "app", check=True, capture_output=True, text=True).stdout)
    workspace = set(meta["workspace_members"])
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    packages = {p["id"]: p for p in meta["packages"]}
    seen, stack = set(), list(workspace)
    while stack:
        pid = stack.pop()
        if pid in seen:
            continue
        seen.add(pid)
        for dep in nodes[pid]["deps"]:
            if any(k["kind"] in (None, "build") for k in dep["dep_kinds"]):
                stack.append(dep["pkg"])
    deps = [packages[p] for p in seen if p not in workspace]
    return sorted(deps, key=lambda p: (p["name"], p["version"]))


def render(deps: list[dict]) -> str:
    lines = [
        "# Third-party notices",
        "",
        "Ascension — Rise of Man is the author's work and is licensed under the terms in",
        "[LICENSE](LICENSE). It is built with the following third-party components, which remain",
        "under their own licences; their copyright notices and licence texts are kept by their",
        "authors at the linked sources. None of these licences is changed by the game's licence.",
        "",
        "This file is generated by `scripts/release/third_party_notices.py`.",
        "",
        "## Other components",
        "",
        "| Component | Licence | Licence text |",
        "| --- | --- | --- |",
    ]
    lines += [f"| {n} | {lic} | `{where}` |" for n, lic, where in OTHERS]
    lines += [
        "",
        f"## Rust crates ({len(deps)})",
        "",
        "| Crate | Version | Licence | Source |",
        "| --- | --- | --- | --- |",
    ]
    for p in deps:
        source = p.get("repository") or f"https://crates.io/crates/{p['name']}"
        licence = (p.get("license") or "see source").replace("|", "/")
        lines.append(f"| {p['name']} | {p['version']} | {licence} | {source} |")
    return "\n".join(lines) + "\n"


def main() -> int:
    text = render(rust_dependencies())
    if "--check" in sys.argv:
        current = OUT.read_text() if OUT.exists() else ""
        if current != text:
            print("THIRD-PARTY-NOTICES.md is out of date; run scripts/release/third_party_notices.py")
            return 1
        print("THIRD-PARTY-NOTICES.md is up to date")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
